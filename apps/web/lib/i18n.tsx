const DICTS: Record<Locale, Dict> = { fr, ht, en };

export type TFunc = (key: string, vars?: Record<string, string | number>) => string;

function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

interface I18nState {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: TFunc;
}

const I18nCtx = createContext<I18nState | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('fr');

  useEffect(() => {
    try {
      const stored = localStorage.getItem(LOCALE_KEY) as Locale | null;
      if (stored && (stored === 'fr' || stored === 'ht' || stored === 'en')) setLocaleState(stored);
    } catch { /* ignore */ }
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try { localStorage.setItem(LOCALE_KEY, l); } catch { /* ignore */ }
    if (typeof document !== 'undefined') document.documentElement.lang = l;
  }, []);

  const t = useCallback<TFunc>((key, vars) => {
    const table = DICTS[locale];
    const raw = table[key] ?? en[key] ?? key;
    return interpolate(raw, vars);
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

/** Convenience hook when a component only needs the translator. */
export function useT(): TFunc {
  return useI18n().t;
}

/** Localized countdown label from a numeric day delta + tone. */
export function countdownLabel(cd: { days: number; tone: string } | null, t: TFunc): string {
  if (!cd) return '';
  if (cd.days < 0) return t('cd.overdue', { n: Math.abs(cd.days) });
  if (cd.days === 0) return t('cd.dueToday');
  return t('cd.left', { n: cd.days });
}
